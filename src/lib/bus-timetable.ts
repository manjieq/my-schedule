// The ERICA campus shuttle timetable, transcribed from the university's
// "셔틀버스 노선 및 시간표 (중앙역 경유)" PDF (2026). Bundled rather than fetched:
// the app has no network access by design, so a new timetable means a new
// build with this file updated.
//
// Each column is a list of rows, one per hour: the two-digit hour, then that
// hour's departure minutes. A minute's suffix is its route:
//
//   (none)  direct (the PDF's D / DH)
//   Y       direct to the Terminal (the PDF's DY). Only printed in the
//           Residence column; from Shuttlecock those buses are their own column
//   C       the cycle route: Shuttlecock -> Handaeap -> Terminal -> Shuttlecock
//   J       detours via Jungang Station on the way to Handaeap (중앙역 경유)
//
// Columns are departures from one stop:
//
//   residence            ERICA Residence (창의인재원), every bus goes to Shuttlecock
//   shuttlecock          Shuttlecock (셔틀콕) towards Handaeap; the C buses
//                        carry on to the Terminal
//   shuttlecockTerminal  Shuttlecock direct to the Terminal (DY), weekdays only
//   handaeap             Handaeap Station (한대앞역), back to campus
//   terminal             Yesulin APT / Ansan Bus Terminal (예술인APT), back to campus
//
// One correction to the PDF as printed: the green "19:00" written inside the
// 18:00 Handaeap cell on the semester and session weekday tables is the 18:50
// direct bus from Shuttlecock leaving Handaeap, so it is entered here as a
// 19:00 departure.
//
// Generated from the PDF's text layer by cell position, then checked against
// the rendered page. bus-timetable.test.ts pins a sample of cells so an edit
// to this file that drifts from the PDF fails loudly.

export type TimetableColumn = readonly string[];

